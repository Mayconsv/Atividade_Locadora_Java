    private void Alugar1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Alugar1ActionPerformed
    try {
        // Pega os dados dos campos de texto
        String cpf = TXTCPF.getText();
        String nome = TXTNome1.getText();
        String dataAluguel = Data_Aluguel1.getText();
        String dataDevolucao = Data_Devolucao.getText();
        
        // Pega o carro selecionado na Caixa de Seleção
        String carroEscolhido = Disponiveis.getSelectedItem().toString();
        
        // Validação para garantir que nenhum campo ficou vazio
        if (cpf.isEmpty() || nome.isEmpty() || dataAluguel.isEmpty() || dataDevolucao.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor, preencha todos os campos!", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        // Monta o texto em HTML para aparecer formatado na área de "DADOS"
        String resumo = "<html><body>" +
                        "<b>--- ALUGUEL REGISTRADO ---</b><br>" +
                        "<b>Carro:</b> " + carroEscolhido + "<br>" +
                        "<b>Cliente:</b> " + nome + " | <b>CPF:</b> " + cpf + "<br>" +
                        "<b>Retirada:</b> " + dataAluguel + " | <b>Devolução :</b> " + dataDevolucao + "<br>" +
                        "</body></html>";
                        
        
        ListarCarros.setText(resumo);
        
        JOptionPane.showMessageDialog(this, "Carro alugado com sucesso!");
        // Remove o carro que acabou de ser alugado da caixa de seleção de disponíveis
        // Pega o carro escolhido
String carrosAlugados = Disponiveis.getSelectedItem().toString();

// Adiciona na lista global de carros alugados para aparecer na devolução
Home.carrosAlugados.add(carroEscolhido);

// Remove da lista de disponíveis
Disponiveis.removeItemAt(Disponiveis.getSelectedIndex());
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Ocorreu um erro ao registrar o aluguel.", "Erro", JOptionPane.ERROR_MESSAGE);
    } 
    }//GEN-LAST:event_Alugar1ActionPerformed
    
    public void preencherCarros(ArrayList<Carro> listaCarros) {
    Disponiveis.removeAllItems(); // Remove o "Item 1" padrão
    for (Carro c : listaCarros) {
        // Adiciona cada carro no JComboBox
        Disponiveis.addItem(c.getModelo() + " - " + c.getPlaca());
    }
    }

